//! Generates linker-satisfying stub definitions for every `extern "C"`
//! item bindgen emitted.
//!
//! When the `test-stubs` feature is enabled, this rewrites `bindings.rs` to
//! drop every `extern "C" { ... }` block and emits an alongside `bindings_stubs.rs`
//! containing `#[unsafe(no_mangle)]` definitions of the dropped items. The
//! crate then includes both files at the same module scope, so the type
//! references in the stub signatures resolve against the surviving types
//! in `bindings.rs`.
//!
//! Stub bodies always `unimplemented!()` — they exist solely to satisfy the
//! linker when downstream test binaries don't have libzsh available at
//! link time. Variadic functions are emitted with the `...` dropped from
//! their signature; this is C-ABI-compatible (callee ignores extras) and
//! the stub panics before reading anything anyway.
//!
//! Statics are zero-initialized via `core::mem::zeroed()`, which is
//! `const`-stable as of Rust 1.75 and safe for every static currently in
//! the zsh bindings (all are scalar, pointer, array-of-scalar, or POD
//! struct types).

use std::fs;
use std::io;

use quote::{ToTokens, format_ident, quote};
use syn::{FnArg, ForeignItem, ForeignItemFn, ForeignItemStatic, Item, Pat, PatIdent};

use crate::build::traits::{MaybeSplitToStubs, WriteToFile};

struct Stubs {
    bindings: String,
    stubs: String,
}

impl WriteToFile for Stubs {
    fn write_to_file<P: AsRef<std::path::Path>>(&self, bindings_path: P) -> std::io::Result<()> {
        let path = bindings_path.as_ref();
        let stubs_path = path.with_file_name(format!(
            "{}_stubs{}",
            path.file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("bindings"),
            path.extension()
                .and_then(|s| s.to_str())
                .map_or("".into(), |ext| format!(".{ext}"))
        ));
        fs::write(path, &self.bindings)?;
        fs::write(stubs_path, &self.stubs)?;
        Ok(())
    }
}

impl MaybeSplitToStubs for bindgen::Bindings {
    fn maybe_split_to_stubs(self) -> io::Result<impl WriteToFile> {
        let mut buffer = Vec::new();
        self.write(Box::new(&mut buffer))
            .expect("Failed to write bindings to buffer");

        let src = String::from_utf8(buffer).expect("Invalid UTF-8 in bindings");
        let mut file: syn::File = syn::parse_str(&src).map_err(io::Error::other)?;
        let mut stubs = String::from(
            "// AUTOGENERATED by zsh-sys/build/stubs.rs (feature = \"test-stubs\"). DO NOT EDIT.\n\n",
        );

        file.items.retain(|item| {
            let Item::ForeignMod(fm) = item else {
                return true;
            };
            for fi in &fm.items {
                match fi {
                    ForeignItem::Fn(f) => stubs.push_str(&f.render_stub()),
                    ForeignItem::Static(s) => stubs.push_str(&s.render_stub()),
                    _ => {}
                }
            }
            false
        });

        Ok(Stubs {
            bindings: file.into_token_stream().to_string(),
            stubs: stubs,
        })
    }
}

trait RenderStub {
    fn render_stub(&self) -> String;
}

impl RenderStub for ForeignItemFn {
    fn render_stub(&self) -> String {
        let name = &self.sig.ident;
        let output = &self.sig.output;
        let generics = &self.sig.generics;
        let msg = format!("TEST STUB zsh-sys: {}", name);

        // Rename every param to `_arg{N}`. The body never reads them, and the
        // `_` prefix both silences unused-variable warnings and avoids shadowing
        // any same-named statics in scope (e.g. `pub static mut path`).
        let inputs: Vec<_> = self
            .sig
            .inputs
            .iter()
            .enumerate()
            .map(|(i, arg)| match arg {
                FnArg::Typed(pt) => {
                    let mut pt = pt.clone();
                    pt.pat = Box::new(Pat::Ident(PatIdent {
                        attrs: Vec::new(),
                        by_ref: None,
                        mutability: None,
                        ident: format_ident!("_arg{}", i),
                        subpat: None,
                    }));
                    FnArg::Typed(pt)
                }
                FnArg::Receiver(_) => arg.clone(), // never appears in extern fns
            })
            .collect();

        let tokens = quote! {
            #[unsafe(no_mangle)]
            pub unsafe extern "C" fn #name #generics (#(#inputs),*) #output {
                unimplemented!(#msg)
            }
        };
        tokens.to_string() + "\n\n"
    }
}

impl RenderStub for ForeignItemStatic {
    fn render_stub(&self) -> String {
        let name = &self.ident;
        let ty = &self.ty;
        let mutability = &self.mutability;

        let tokens = quote! {
            #[unsafe(no_mangle)]
            pub static #mutability #name: #ty = unsafe { core::mem::zeroed() };
        };
        tokens.to_string() + "\n\n"
    }
}
